import { visualHeroSources } from './media.ts';

/** Smaller delivery assets are built locally; the existing remote WebP stays untouched. */
export const HERO_DELIVERY_WIDTHS = [480, 720] as const;
export const HERO_DELIVERY_QUALITY = 84;
export const HERO_MAX_DIMENSION = 8192;
export const HERO_MAX_PIXELS = 32_000_000;
export const HERO_METADATA_CONCURRENCY = 6;
export const HERO_METADATA_ATTEMPTS = 3;
const HERO_METADATA_RETRY_DELAY_MS = 250;

export const HERO_REMOTE_PATTERNS = [
  { protocol: 'https', hostname: 'media.aitamer.news', pathname: '/heroes/*' },
  { protocol: 'https', hostname: 'bots.aitamer.news', pathname: '/heroes/*' },
] as const;

export const HERO_SIZES = {
  lead: '(max-width: 900px) calc(100vw - 32px), (max-width: 1232px) calc(100vw - 420px), 812px',
  'home-card': '(max-width: 591.98px) calc(100vw - 32px), (max-width: 900px) calc(50vw - 30px), (max-width: 979.98px) calc(100vw - 420px), (max-width: 1232px) calc(50vw - 224px), 392px',
  listing: '(max-width: 720px) calc(100vw - 32px), (max-width: 900px) calc(50vw - 30px), (max-width: 1232px) calc((100vw - 88px) / 3), 381.34px',
  article: '(max-width: 812px) calc(100vw - 32px), 780px',
} as const;

export type HeroContext = keyof typeof HERO_SIZES;
export type HeroMetadata = { width: number; height: number; format: string };
type Probe = (src: string) => Promise<HeroMetadata>;
export type HeroTransform = {
  src: string;
  width: number;
  height: number;
  format: 'webp';
  quality: number;
  /** Only integer rounding changes the source ratio; never crop the image. */
  fit: 'fill';
};
type Transform = (options: HeroTransform) => Promise<{ src: string }>;
type Sources = ReturnType<typeof visualHeroSources>;
type Candidate = { src: string; width: number; height: number };
export type ResponsiveHero = { candidates: Candidate[]; diagnostic?: string };

/** Cache one bounded/retried metadata promise per URL for the current build's module lifetime. */
export function createHeroMetadataCache({
  retryDelay = (ms: number) => new Promise<void>((done) => setTimeout(done, ms)),
}: { retryDelay?: (ms: number) => Promise<void> } = {}) {
  const metadata = new Map<string, Promise<HeroMetadata>>();
  const waiting: Array<() => void> = [];
  let active = 0;
  const withPermit = async (src: string, probe: Probe): Promise<HeroMetadata> => {
    if (active >= HERO_METADATA_CONCURRENCY) await new Promise<void>((ready) => waiting.push(ready));
    else active++;
    try {
      // Never release a permit on a raced timer: the native probe has no abort API and must settle.
      return await probe(src);
    } finally {
      const next = waiting.shift();
      if (next) next(); // Transfer this live permit directly to the oldest waiter.
      else active--;
    }
  };
  return (src: string, probe: Probe): Promise<HeroMetadata> => {
    let pending = metadata.get(src);
    if (!pending) {
      pending = Promise.resolve().then(async () => {
        for (let attempt = 1; ; attempt++) {
          try { return await withPermit(src, probe); }
          catch (error) {
            if (attempt >= HERO_METADATA_ATTEMPTS) throw error;
            // Backoff holds no request permit, so another URL can make progress meanwhile.
            await retryDelay(HERO_METADATA_RETRY_DELAY_MS * attempt);
          }
        }
      });
      metadata.set(src, pending);
    }
    return pending;
  };
}

export const cachedHeroMetadata = createHeroMetadataCache();

function validDimensions(value: HeroMetadata): boolean {
  return Number.isSafeInteger(value.width) && value.width > 0
    && Number.isSafeInteger(value.height) && value.height > 0
    && value.width <= HERO_MAX_DIMENSION && value.height <= HERO_MAX_DIMENSION
    && value.width * value.height <= HERO_MAX_PIXELS;
}

/**
 * Pure delivery planning with injected I/O. Call the transform on EVERY render: Astro records
 * page dependencies in getImage, even when its underlying generated bytes are already cached.
 */
export async function planResponsiveHero(
  sources: Sources,
  { probe, transform }: { probe: Probe; transform: Transform },
): Promise<ResponsiveHero> {
  const fallback = (diagnostic: string): ResponsiveHero => ({ candidates: [], diagnostic });
  // Re-check the exact pair: local overrides, SVG covers and unknown URLs never reach remote I/O.
  const owned = visualHeroSources(sources.src, undefined);
  if (!sources.webp || owned.webp !== sources.webp || owned.src !== sources.src) {
    return fallback('source is not an owned production JPEG/WebP pair (or media override is active)');
  }

  try {
    const [jpeg, webp] = await Promise.all([probe(sources.src), probe(sources.webp)]);
    if (!validDimensions(jpeg) || !validDimensions(webp)
      || !['jpg', 'jpeg'].includes(jpeg.format) || webp.format !== 'webp') {
      return fallback('unknown image dimensions or unexpected source format');
    }
    // Existing derivatives may round to the nearest pixel; a different composition is not a pair.
    const expectedHeight = jpeg.height * webp.width / jpeg.width;
    if (Math.abs(webp.height - expectedHeight) > 1) {
      return fallback('JPEG and WebP aspect ratios disagree');
    }
    if (webp.width > jpeg.width) return fallback('WebP exceeds the original JPEG width');
    const widths = [...new Set(HERO_DELIVERY_WIDTHS)]
      .filter((width) => width < jpeg.width && width < webp.width);
    if (!widths.length) return fallback('sources are too small for delivery variants');

    const generated = await Promise.all(widths.map(async (width) => {
      const height = Math.round(width * jpeg.height / jpeg.width);
      const image = await transform({
        src: sources.src, width, height, format: 'webp', quality: HERO_DELIVERY_QUALITY, fit: 'fill',
      });
      if (!image.src || image.src === sources.src || image.src === sources.webp) {
        throw new Error('image service did not generate a delivery asset');
      }
      return { src: image.src, width, height };
    }));
    return { candidates: [...generated, { src: sources.webp, width: webp.width, height: webp.height }] };
  } catch (error) {
    return fallback(`metadata or delivery planning failed: ${error instanceof Error ? error.message : String(error)}`);
  }
}
